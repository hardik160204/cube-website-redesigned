-- Uploaded images (the files themselves are in the "media" Storage bucket).
CREATE TABLE IF NOT EXISTS media (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  file text NOT NULL UNIQUE,
  original_name text NOT NULL,
  mime text NOT NULL,
  size integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Single demo slots the admin closed ("block") or added ("open"), on top of the weekly hours.
CREATE TABLE IF NOT EXISTS slot_rules (
  slot_start text PRIMARY KEY,
  action text NOT NULL CHECK (action IN ('block', 'open')),
  updated_at timestamptz NOT NULL DEFAULT now()
);

