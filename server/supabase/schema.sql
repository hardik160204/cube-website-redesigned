-- Admin accounts. Passwords live in Supabase Auth; this table says which Auth users may use /admin.
CREATE TABLE IF NOT EXISTS admins (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL,
  auth_user_id uuid NOT NULL UNIQUE,
  failed_attempts integer NOT NULL DEFAULT 0,
  locked_until bigint NOT NULL DEFAULT 0,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS admins_email ON admins (lower(email));

-- Signed-in admin sessions (only a hash of each session token is stored).
CREATE TABLE IF NOT EXISTS sessions (
  token_hash text PRIMARY KEY,
  admin_id integer NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);

-- Demo bookings from /demo.
CREATE TABLE IF NOT EXISTS bookings (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slot_start text NOT NULL,
  timezone text NOT NULL,
  name text NOT NULL,
  email text NOT NULL,
  phone text NOT NULL,
  company text NOT NULL,
  designation text NOT NULL DEFAULT '',
  users text NOT NULL DEFAULT '',
  interest text NOT NULL DEFAULT '',
  message text NOT NULL DEFAULT '',
  status text NOT NULL DEFAULT 'scheduled' CHECK (status IN ('scheduled', 'completed', 'cancelled')),
  consent_at timestamptz NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now()
);
-- One live booking per time slot.
CREATE UNIQUE INDEX IF NOT EXISTS bookings_slot_live ON bookings (slot_start) WHERE status <> 'cancelled';

