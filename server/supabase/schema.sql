-- Public "media" bucket for uploaded pictures and videos: anyone can view; uploads need a one-file upload
-- link the server signs, and the server checks each file's real type afterwards. Images up to 10 MB and
-- MP4/WebM video up to 50 MB (the server enforces the per-type limits). An existing bucket is changed to
-- these limits with the Storage API (see the README), since this database login can't alter Storage's tables.
DO $$ BEGIN
  IF EXISTS (SELECT 1 FROM pg_namespace WHERE nspname = 'storage') THEN
    INSERT INTO storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
    VALUES ('media', 'media', true, 52428800, ARRAY['image/jpeg', 'image/png', 'image/gif', 'image/webp', 'image/avif', 'video/mp4', 'video/webm'])
    ON CONFLICT (id) DO NOTHING;
  END IF;
END $$;
