-- Sessions end after 30 minutes without activity, as well as after 12 hours in total.
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS last_seen bigint NOT NULL DEFAULT 0;

-- Second sign-in step: a 6-digit code from the admin's authenticator app (TOTP). The encrypted secret is
-- stored once the admin enrols their app.
ALTER TABLE admins ADD COLUMN IF NOT EXISTS totp_secret text;

-- The pending state between the password step and the authenticator-code step. Only a hash of the pending
-- token is stored; it expires after 10 minutes or 5 wrong codes. During first-time enrolment, pending_secret
-- holds the new (encrypted) authenticator secret until the admin confirms it with a code.
CREATE TABLE IF NOT EXISTS login_challenges (
  token_hash text PRIMARY KEY,
  admin_id integer NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  attempts integer NOT NULL DEFAULT 0,
  pending_secret text
);
ALTER TABLE login_challenges ADD COLUMN IF NOT EXISTS pending_secret text;

-- Security and processing log: sign-ins, failed attempts and every admin change, with the IP address.
-- Kept 1 year (DPDP Rules: 1 year of processing logs; CERT-In: at least 180 days), then deleted.
CREATE TABLE IF NOT EXISTS audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  admin_id integer REFERENCES admins(id) ON DELETE SET NULL,
  email text NOT NULL DEFAULT '',
  action text NOT NULL,
  detail text NOT NULL DEFAULT '',
  ip text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS audit_log_at ON audit_log (at);

-- Page views, recorded only for visitors who allowed analytics. No IP address, cookie or visitor id is
-- stored: just the page, the referring site and the kind of device. Deleted after 13 months.
CREATE TABLE IF NOT EXISTS page_views (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  path text NOT NULL,
  referrer text NOT NULL DEFAULT '',
  device text NOT NULL DEFAULT '',
  browser text NOT NULL DEFAULT '',
  os text NOT NULL DEFAULT '',
  lang text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS page_views_at ON page_views (at);

-- Dashboard settings (sales emails, demo hours, retention).
CREATE TABLE IF NOT EXISTS settings (
  key text PRIMARY KEY,
  value jsonb NOT NULL
);

-- The dashboard sections each admin may open, chosen by the owner (e.g. ["bookings","blog"]). The owner
-- always has every section, plus the activity log and admin accounts, whatever is stored here.
ALTER TABLE admins ADD COLUMN IF NOT EXISTS permissions jsonb NOT NULL DEFAULT '[]'::jsonb;

-- Pages built in the dashboard's Pages section, served at their own address with the site's page layout.
-- content holds the hero, the sections and the closing call to action.
CREATE TABLE IF NOT EXISTS pages (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  path text NOT NULL UNIQUE,
  title text NOT NULL,
  description text NOT NULL DEFAULT '',
  published boolean NOT NULL DEFAULT false,
  content jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now()
);

-- Card lists changed in the visual editor (product cards, feature cards, steps, check lists, FAQs): the
-- whole list as the admin left it, on one page (scope = its path) or on every page (scope = "*").
CREATE TABLE IF NOT EXISTS lists (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope text NOT NULL,
  key text NOT NULL,
  items jsonb NOT NULL,
  updated_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (scope, key)
);

