CREATE TABLE IF NOT EXISTS slot_rules (
  slot_start text PRIMARY KEY,
  action text NOT NULL CHECK (action IN ('block', 'open')),
  updated_at timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE bookings ADD COLUMN IF NOT EXISTS terms_version text NOT NULL DEFAULT '';
ALTER TABLE leads ADD COLUMN IF NOT EXISTS terms_version text NOT NULL DEFAULT '';
ALTER TABLE consents ADD COLUMN IF NOT EXISTS created_at timestamptz NOT NULL DEFAULT now();
ALTER TABLE sessions ADD COLUMN IF NOT EXISTS last_seen bigint NOT NULL DEFAULT 0;

CREATE TABLE IF NOT EXISTS login_challenges (
  token_hash text PRIMARY KEY,
  admin_id integer NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  expires_at bigint NOT NULL,
  attempts integer NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS audit_log (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  admin_id integer REFERENCES admins(id) ON DELETE SET NULL,
  email text NOT NULL DEFAULT '',
  action text NOT NULL,
  detail text NOT NULL DEFAULT '',
  ip text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS audit_log_at ON audit_log (at);

CREATE TABLE IF NOT EXISTS page_views (
  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  path text NOT NULL,
  referrer text NOT NULL DEFAULT '',
  device text NOT NULL DEFAULT '',
  browser text NOT NULL DEFAULT '',
  os text NOT NULL DEFAULT '',
  lang text NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS page_views_at ON page_views (at);

